// Shared offline asset pipeline helpers: scan the asset tree, render the Metro index, and cross-check references from
// every content origin (university packs in data/question-packs, LibraryPacks in data/library-packs).
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { assetPathProblem, collectQuestionAssetRefs } from "../../src/services/assetRefs.mjs";

export const DATA_ROOT = (root) => resolve(root, "data/question-packs");
export const ASSET_ROOT = (root) => join(DATA_ROOT(root), "assets");
export const LIBRARY_PACK_DIR = (root) => resolve(root, "data/library-packs");

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
}

/** Every asset file as a key relative to data/question-packs (e.g. "assets/ru-v/ab12.png"), sorted, with path problems. */
export function scanAssets(root) {
  const base = DATA_ROOT(root);
  const keys = walk(ASSET_ROOT(root)).filter((p) => statSync(p).isFile()).map((p) => relative(base, p).split("\\").join("/")).sort();
  const problems = [];
  for (const key of keys) {
    const problem = assetPathProblem(key);
    if (problem) problems.push(`Asset file "${key}" ${problem}.`);
  }
  return { keys, problems };
}

/** All asset references (with their owner) from university packs and LibraryPacks. */
export function collectPackRefs(root) {
  const refs = [];
  const read = (dir, filter, origin) => {
    if (!existsSync(dir)) return;
    for (const name of readdirSync(dir).filter(filter).sort()) {
      const json = JSON.parse(readFileSync(join(dir, name), "utf8"));
      for (const q of Array.isArray(json.questions) ? json.questions : []) {
        for (const r of collectQuestionAssetRefs(q)) refs.push({ origin, pack: name, question: q.id, ...r });
      }
    }
  };
  read(DATA_ROOT(root), (n) => n.endsWith(".json"), "question-pack");
  read(LIBRARY_PACK_DIR(root), (n) => n.endsWith(".json"), "library-pack");
  return refs;
}

/** Reference problems: missing files, invalid paths. Orphans (unreferenced files) are reported separately as warnings. */
export function checkRefs(root) {
  const { keys, problems } = scanAssets(root);
  const have = new Set(keys);
  const refs = collectPackRefs(root);
  const errors = [...problems];
  for (const r of refs) {
    const p = assetPathProblem(r.path);
    if (p) errors.push(`${r.pack} ${r.question}: asset "${r.path}" ${p}.`);
    else if (!have.has(r.path)) errors.push(`${r.pack} ${r.question}: ${r.kind} asset "${r.path}" does not exist.`);
  }
  const used = new Set(refs.map((r) => r.path));
  const orphans = keys.filter((k) => !used.has(k));
  return { errors, warnings: orphans.map((k) => `Asset "${k}" is not referenced by any pack.`), refCount: refs.length, uniqueRefs: used.size, assetCount: keys.length };
}

/** Renders src/content/questionAssets.ts for the given keys. */
export function renderIndex(keys) {
  const entries = keys.map((key) => `  ${JSON.stringify(key)}: require(${JSON.stringify("../../data/question-packs/" + key)}),`);
  return [
    "// GENERATED by scripts/build-question-assets.mjs. Do not edit by hand.",
    'import type { ImageSourcePropType } from "react-native";',
    "",
    "// One offline registry for every content origin (university packs and LibraryPacks). Metro needs static require() calls.",
    "const QUESTION_ASSETS: Readonly<Record<string, ImageSourcePropType>> = {",
    ...entries,
    "};",
    "",
    "export function hasQuestionAsset(path: string): boolean {",
    "  return Object.prototype.hasOwnProperty.call(QUESTION_ASSETS, path);",
    "}",
    "",
    "export function getQuestionAssetSource(path: string): ImageSourcePropType | null {",
    "  return hasQuestionAsset(path) ? QUESTION_ASSETS[path]! : null;",
    "}",
    "",
    "/** Resolves only the assets that exist; use resolveQuestionAssets() when a missing file must stay visible. */",
    "export function getQuestionAssetSources(paths: readonly string[]): ImageSourcePropType[] {",
    "  const sources: ImageSourcePropType[] = [];",
    "  for (const path of paths) {",
    "    const source = getQuestionAssetSource(path);",
    "    if (source) sources.push(source);",
    "  }",
    "  return sources;",
    "}",
    "",
    "/** One entry per requested path, in order. `source` is null when the file is not bundled (shown as a placeholder, never dropped). */",
    "export function resolveQuestionAssets(paths: readonly string[]): { path: string; source: ImageSourcePropType | null }[] {",
    "  return paths.map((path) => ({ path, source: getQuestionAssetSource(path) }));",
    "}",
    "",
    "export const QUESTION_ASSET_COUNT = " + keys.length + ";",
    "",
  ].join("\n");
}
