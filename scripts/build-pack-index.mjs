#!/usr/bin/env node
// Generates src/content/bundledPacks.ts from data/question-packs/*.json so packs are bundled into the app.
// Every pack is validated first; a single invalid pack aborts the build with actionable errors.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { validateQuestionPack } from "../src/services/questionPackValidator.mjs";

const here = dirname(fileURLToPath(import.meta.url));

export function buildIndex(packDir = resolve(here, "../data/question-packs"), outFile = resolve(here, "../src/content/bundledPacks.ts")) {
  const files = readdirSync(packDir).filter((f) => f.endsWith(".json")).sort();
  const problems = [];
  for (const file of files) {
    let pack;
    try {
      pack = JSON.parse(readFileSync(join(packDir, file), "utf8"));
    } catch (error) {
      problems.push(`${file}: not valid JSON (${error.message})`);
      continue;
    }
    const result = validateQuestionPack(pack);
    if (!result.valid) problems.push(...result.errors.map((e) => `${file}: ${e}`));
  }
  if (problems.length) return { ok: false, problems, files };
  let rel = relative(dirname(outFile), packDir).split("\\").join("/");
  if (!rel.startsWith(".")) rel = rel ? "./" + rel : ".";
  const imports = files.map((f, i) => `import pack${i} from "${rel}/${f}";`).join("\n");
  const list = files.map((_, i) => `pack${i}`).join(", ");
  const body = `// GENERATED by scripts/build-pack-index.mjs from data/question-packs/*.json. Do not edit by hand.\n${imports}${imports ? "\n\n" : ""}export const BUNDLED_PACKS: readonly unknown[] = [${list}];\n`;
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, body);
  return { ok: true, problems: [], files };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = buildIndex();
  if (!result.ok) {
    console.error("Question pack index NOT generated:\n" + result.problems.map((p) => "  - " + p).join("\n"));
    process.exit(1);
  }
  console.log(`Bundled ${result.files.length} question pack(s) into src/content/bundledPacks.ts`);
}
