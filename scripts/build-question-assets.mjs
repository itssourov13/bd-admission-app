#!/usr/bin/env node
// Generates a static Metro asset map for local question images. JSON asset paths
// are dynamic at runtime, so they cannot be passed directly to require().
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const assetDir = resolve(here, "../data/question-packs/assets/lokkho");
const outFile = resolve(here, "../src/content/questionAssets.ts");

const files = existsSync(assetDir)
  ? readdirSync(assetDir).filter((file) => statSync(join(assetDir, file)).isFile()).sort()
  : [];
const unsupported = files.filter((file) => !/\.png$/i.test(file));
if (unsupported.length) {
  console.error("Question assets must be normalized to PNG before indexing: " + unsupported.join(", "));
  process.exit(1);
}

const entries = files.map((file) => {
  const key = `assets/lokkho/${file}`;
  const localPath = `../../data/question-packs/assets/lokkho/${file}`;
  return `  ${JSON.stringify(key)}: require(${JSON.stringify(localPath)}),`;
});
const body = [
  "// GENERATED by scripts/build-question-assets.mjs. Do not edit by hand.",
  'import type { ImageSourcePropType } from "react-native";',
  "",
  "const QUESTION_ASSETS: Readonly<Record<string, ImageSourcePropType>> = {",
  ...entries,
  "};",
  "",
  "export function getQuestionAssetSources(paths: readonly string[]): ImageSourcePropType[] {",
  "  const sources: ImageSourcePropType[] = [];",
  "  for (const path of paths) {",
  "    const source = QUESTION_ASSETS[path];",
  "    if (source) sources.push(source);",
  "  }",
  "  return sources;",
  "}",
  "",
].join("\n");

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body, "utf8");
console.log(`Indexed ${files.length} local question asset(s) into src/content/questionAssets.ts`);
