#!/usr/bin/env node
// Content build: validates data/question-packs/*.json, then generates:
// - src/content/bundledManifest.ts (small, committed manifest)
// - assets/content/content_seed.db (gitignored SQLite seed built by real migrations + importer)
//
// node scripts/build-content.mjs            always rebuild
// node scripts/build-content.mjs --ensure   rebuild only when the asset is missing, stale, or invalid
// node scripts/build-content.mjs --check    write nothing; fail when the manifest or seed is stale/invalid
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { validateQuestionPack } from "../src/services/questionPackValidator.mjs";
import { packSignature } from "../src/services/importer.ts";
import { LATEST_VERSION } from "../src/db/schema.ts";
import { buildSeedDatabase } from "../src/services/seedBuilder.ts";
import { computeSeedId, SEED_FORMAT } from "../src/content/seedFormat.ts";
import { openNodeDb } from "./lib/node-sqlite-db.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const DEFAULTS = {
  packDir: resolve(here, "../data/question-packs"),
  manifestFile: resolve(here, "../src/content/bundledManifest.ts"),
  seedFile: resolve(here, "../assets/content/content_seed.db")
};

export function renderManifest(manifest) {
  const rows = manifest.packs.map((p) =>
    "  { batchId: " + JSON.stringify(p.batchId) + ", signature: " +
    JSON.stringify(p.signature) + ", questions: " + p.questions + " }"
  );
  return (
    "// GENERATED by scripts/build-content.mjs from data/question-packs/*.json. Do not edit by hand.\n" +
    'import type { ContentManifest } from "./seedFormat.ts";\n\n' +
    "export const BUNDLED_MANIFEST: ContentManifest = {\n" +
    "  seedFormat: " + manifest.seedFormat + ",\n  seedId: " + JSON.stringify(manifest.seedId) + ",\n" +
    "  packs: [" + (rows.length ? "\n" + rows.join(",\n") + "\n  " : "") + "]\n};\n"
  );
}

function readPacks(packDir) {
  const files = readdirSync(packDir).filter((f) => f.endsWith(".json")).sort();
  const problems = [];
  const packs = [];
  for (const file of files) {
    let pack;
    try {
      pack = JSON.parse(readFileSync(join(packDir, file), "utf8"));
    } catch (error) {
      problems.push(file + ": not valid JSON (" + error.message + ")");
      continue;
    }
    const result = validateQuestionPack(pack);
    if (!result.valid) problems.push(...result.errors.map((e) => file + ": " + e));
    packs.push(pack);
  }
  return { files, packs, problems };
}

function countRows(db, table) {
  // The table name always comes from this script's fixed allowlist, never user input.
  return Number(db.prepare("SELECT COUNT(*) AS count FROM " + table).get().count);
}

function expectedContentCounts(packs) {
  const institutions = new Set();
  const papers = new Set();
  const rules = new Set();
  const sourceDocuments = new Set();
  const replacePapers = new Set();
  const appearances = new Set();
  let questions = 0;
  let options = 0;

  for (const pack of packs) {
    for (const item of pack.institutions) institutions.add(item.id);
    for (const item of pack.papers) papers.add(item.id);
    for (const item of pack.examRules) rules.add(item.id);
    for (const item of pack.sourceDocuments) sourceDocuments.add(item.id);
    if (pack.replaceExistingPaperContent) {
      for (const paper of pack.papers) replacePapers.add(JSON.stringify([pack.batch.id, paper.id]));
    }
    for (const question of pack.questions) {
      questions += 1;
      options += question.options.length;
      for (const appearance of question.appearances) {
        // Mirrors uq_appearance: NULL question/page numbers are treated as zero.
        appearances.add(JSON.stringify([
          question.id, appearance.paperId,
          appearance.questionNumber ?? 0, appearance.pageNumber ?? 0
        ]));
      }
    }
  }

  return {
    institutions: institutions.size,
    exam_papers: papers.size,
    exam_rules: rules.size,
    question_batches: packs.length,
    source_documents: sourceDocuments.size,
    questions,
    question_options: options,
    question_sources: questions,
    question_appearances: appearances.size,
    seed_packs: packs.length,
    seed_replace_papers: replacePapers.size
  };
}

/** Validate physical SQLite integrity and logical agreement with the source JSON/manifest. */
export function inspectSeed(seedFile, manifest, packs) {
  if (!existsSync(seedFile)) return { ok: false, problems: ["seed file is missing"] };
  let db;
  try {
    db = new DatabaseSync(seedFile, { readOnly: true });

    const integrity = db.prepare("PRAGMA quick_check").all();
    if (integrity.length !== 1 || integrity[0].quick_check !== "ok") {
      return { ok: false, problems: ["SQLite quick_check failed: " + JSON.stringify(integrity.slice(0, 3))] };
    }
    const foreignKeyIssues = db.prepare("PRAGMA foreign_key_check").all();
    if (foreignKeyIssues.length > 0) {
      return { ok: false, problems: ["SQLite foreign_key_check found " + foreignKeyIssues.length + " issue(s)"] };
    }

    const schemaVersion = Number(db.prepare("PRAGMA user_version").get().user_version);
    if (schemaVersion !== LATEST_VERSION) {
      return { ok: false, problems: ["seed schema is v" + schemaVersion + "; expected v" + LATEST_VERSION] };
    }

    const metadata = new Map(db.prepare("SELECT key, value FROM seed_meta").all().map((row) => [row.key, row.value]));
    if (metadata.get("format") !== String(SEED_FORMAT)) {
      return { ok: false, problems: ["seed format is " + (metadata.get("format") ?? "missing") + "; expected " + SEED_FORMAT] };
    }
    if (metadata.get("seed_id") !== manifest.seedId) {
      return { ok: false, problems: ["seed id does not match the generated manifest"] };
    }

    const seedPacks = db.prepare(
      "SELECT batch_id, ordinal, pack_signature, question_count FROM seed_packs ORDER BY ordinal"
    ).all();
    if (seedPacks.length !== manifest.packs.length) {
      return { ok: false, problems: ["seed has " + seedPacks.length + " pack checkpoints; manifest expects " + manifest.packs.length] };
    }
    for (const [index, expected] of manifest.packs.entries()) {
      const actual = seedPacks[index];
      if (
        actual.batch_id !== expected.batchId ||
        Number(actual.ordinal) !== index ||
        actual.pack_signature !== expected.signature ||
        Number(actual.question_count) !== expected.questions
      ) {
        return { ok: false, problems: ["seed pack checkpoint " + index + " does not match " + expected.batchId] };
      }
    }

    const batchRows = db.prepare(
      "SELECT p.batch_id, p.pack_signature, p.question_count, b.pack_signature AS stored_signature, COUNT(q.id) AS actual_questions " +
      "FROM seed_packs p " +
      "LEFT JOIN question_batches b ON b.id = p.batch_id " +
      "LEFT JOIN questions q ON q.batch_id = p.batch_id " +
      "GROUP BY p.batch_id, p.pack_signature, p.question_count, b.pack_signature " +
      "ORDER BY MIN(p.ordinal)"
    ).all();
    for (const row of batchRows) {
      if (!row.stored_signature || row.stored_signature !== row.pack_signature || Number(row.actual_questions) !== Number(row.question_count)) {
        return { ok: false, problems: ["seed content for " + row.batch_id + " is incomplete or its batch signature differs from the manifest"] };
      }
    }

    const expectedCounts = expectedContentCounts(packs);
    for (const [table, expected] of Object.entries(expectedCounts)) {
      const actual = countRows(db, table);
      if (actual !== expected) {
        return { ok: false, problems: ["seed table " + table + " has " + actual + " rows; source packs expect " + expected] };
      }
    }

    // The distributable seed must never contain a student's local records.
    for (const table of ["user_profile", "bookmarks", "practice_sessions", "session_questions", "session_answers"]) {
      const rows = countRows(db, table);
      if (rows !== 0) return { ok: false, problems: ["seed contains " + rows + " row(s) in user-owned table " + table] };
    }

    return { ok: true, problems: [] };
  } catch (error) {
    return { ok: false, problems: ["seed cannot be inspected: " + (error instanceof Error ? error.message : String(error))] };
  } finally {
    db?.close();
  }
}

/** Builds (or checks) the manifest and seed. Returns { ok, problems, files, manifest, seedBuilt, stale }. */
export async function buildContent({ packDir = DEFAULTS.packDir, manifestFile = DEFAULTS.manifestFile, seedFile = DEFAULTS.seedFile, ensure = false, check = false } = {}) {
  const { files, packs, problems } = readPacks(packDir);
  if (problems.length) return { ok: false, problems, files, manifest: null, seedBuilt: false, stale: [] };

  const entries = packs.map((pack) => ({ batchId: pack.batch.id, signature: packSignature(pack), questions: pack.questions.length }));
  const ids = new Set();
  for (const entry of entries) {
    if (ids.has(entry.batchId)) return { ok: false, problems: ["Duplicate batch id " + entry.batchId], files, manifest: null, seedBuilt: false, stale: [] };
    ids.add(entry.batchId);
  }
  const manifest = { seedFormat: SEED_FORMAT, seedId: computeSeedId(entries), packs: entries };
  const manifestText = renderManifest(manifest);
  const stale = [];
  if (!existsSync(manifestFile) || readFileSync(manifestFile, "utf8") !== manifestText) stale.push(manifestFile);

  const seedInspection = inspectSeed(seedFile, manifest, packs);
  if (!seedInspection.ok) stale.push(seedFile);
  if (check) {
    const checkProblems = stale.map((file) => {
      if (file === seedFile) {
        return file + " is invalid or out of date: " + seedInspection.problems.join("; ") + "; run pnpm content:build";
      }
      return file + " is out of date; run pnpm content:build";
    });
    return { ok: stale.length === 0, problems: checkProblems, files, manifest, seedBuilt: false, stale };
  }

  if (stale.includes(manifestFile)) {
    mkdirSync(dirname(manifestFile), { recursive: true });
    writeFileSync(manifestFile, manifestText);
  }
  let seedBuilt = false;
  if (!(ensure && seedInspection.ok)) {
    mkdirSync(dirname(seedFile), { recursive: true });
    const tmp = seedFile + ".tmp";
    for (const suffix of ["", "-journal", "-wal", "-shm"]) rmSync(tmp + suffix, { force: true });
    const db = openNodeDb(tmp);
    try {
      const built = await buildSeedDatabase(db, packs);
      if (built.seedId !== manifest.seedId) throw new Error("Seed id mismatch between manifest and built seed.");
      db.raw.exec("PRAGMA journal_mode = DELETE");
      db.raw.exec("VACUUM");
    } finally {
      db.raw.close();
    }
    // Atomic replacement keeps the previous valid asset in place if seed generation fails.
    renameSync(tmp, seedFile);
    seedBuilt = true;
  }
  return { ok: true, problems: [], files, manifest, seedBuilt, stale };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = new Set(process.argv.slice(2));
  const started = performance.now();
  const result = await buildContent({ ensure: args.has("--ensure"), check: args.has("--check") });
  if (!result.ok) {
    console.error((args.has("--check") ? "Content out of date:\n" : "Content NOT built:\n") + result.problems.map((p) => "  - " + p).join("\n"));
    process.exit(1);
  }
  const seedMb = existsSync(DEFAULTS.seedFile) ? (statSync(DEFAULTS.seedFile).size / 1048576).toFixed(2) : "n/a";
  const questions = result.manifest.packs.reduce((sum, pack) => sum + pack.questions, 0);
  console.log(
    args.has("--check")
      ? "Content up to date: " + result.files.length + " packs, " + questions + " questions, seed " + seedMb + " MiB."
      : "Content " + (result.seedBuilt ? "built" : "already current") + ": " + result.files.length + " packs, " + questions + " questions, seed " + seedMb + " MiB, " + Math.round(performance.now() - started) + " ms."
  );
}
